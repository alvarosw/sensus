export function seedOldTestament(db: DatabaseSync): void {
  insert(db, 'book', OT_BOOKS);
  insert(db, 'source', OT_SOURCES);
  insert(
    db,
    'verse_text',
    OT_VERSES.map(([sourceId, vid, text]) => ({ cite_id: `txt:${sourceId}:${vid}`, source_id: sourceId, vid, text })),
  );
  insert(
    db,
    'text_division',
    OT_DIVISIONS.map(([sourceId, vid, kind, title]) => ({ source_id: sourceId, vid, kind, title })),
  );
  insert(db, 'token', OT_TOKENS);
  insert(db, 'lexicon_entry', OT_LEXICON);
}
